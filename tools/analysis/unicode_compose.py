# unicode_compose.py: writes native/src/engine/text/compose.rs, the canonical compositions of the Unicode
# Character Database as Python's unicodedata has them (a starter and the character after it that compose
# to one code point under NFC; Hangul syllables compose by arithmetic and are not listed).
#
#   python tools/analysis/unicode_compose.py
import os
import unicodedata

pairs = []
for code in range(0x110000):
    decomposition = unicodedata.decomposition(chr(code))
    if not decomposition or decomposition.startswith('<'):
        continue
    parts = [int(part, 16) for part in decomposition.split()]
    if len(parts) != 2:
        continue
    text = chr(parts[0]) + chr(parts[1])
    if unicodedata.normalize('NFC', text) == chr(code):
        pairs.append((parts[0], parts[1], code))
pairs.sort()

lines = [
    '//! Canonical composition (generated by tools/analysis/unicode_compose.py from the Unicode Character',
    '//! Database %s; do not edit): the pairs of a character and the one after it that NFC composes to one' % unicodedata.unidata_version,
    '//! code point. HarfBuzz shapes such a pair as the composed character when the font has its glyph',
    '//! (`Font::shape`).',
    '',
    '/// (first, second, composed), sorted by first then second.',
    'const PAIRS: [(u32, u32, u32); %d] = [' % len(pairs),
]
row = []
for first, second, composed in pairs:
    row.append('(0x%X, 0x%X, 0x%X)' % (first, second, composed))
    if len(row) == 5:
        lines.append('    ' + ', '.join(row) + ',')
        row = []
if row:
    lines.append('    ' + ', '.join(row) + ',')
lines += [
    '];',
    '',
    '/// The code point `first` and `second` compose to, if any (Hangul syllables included).',
    'pub fn compose(first: u32, second: u32) -> Option<u32> {',
    '    // Hangul: a leading consonant and a vowel, then a syllable without a final and a trailing consonant',
    '    if (0x1100..=0x1112).contains(&first) && (0x1161..=0x1175).contains(&second) {',
    '        return Some(0xAC00 + ((first - 0x1100) * 21 + (second - 0x1161)) * 28);',
    '    }',
    '    if (0xAC00..=0xD7A3).contains(&first) && (first - 0xAC00) % 28 == 0 && (0x11A8..=0x11C2).contains(&second) {',
    '        return Some(first + second - 0x11A7);',
    '    }',
    '    PAIRS.binary_search_by_key(&(first, second), |entry| (entry.0, entry.1)).ok().map(|index| PAIRS[index].2)',
    '}',
    '',
    '#[cfg(test)]',
    'mod tests {',
    '    use super::*;',
    '',
    '    #[test]',
    '    fn composes_canonical_pairs_only() {',
    '        assert_eq!(compose(0x65, 0x301), Some(0xE9));',
    '        assert_eq!(compose(0x41, 0x30A), Some(0xC5));',
    '        assert_eq!(compose(0x1100, 0x1161), Some(0xAC00));',
    '        assert_eq!(compose(0xAC00, 0x11A8), Some(0xAC01));',
    '        assert_eq!(compose(0x65, 0x65), None);',
    '        assert_eq!(compose(0x66, 0x301), None);',
    '        assert!(PAIRS.windows(2).all(|pair| (pair[0].0, pair[0].1) < (pair[1].0, pair[1].1)));',
    '    }',
    '}',
    '',
]
here = os.path.dirname(os.path.abspath(__file__))
target = os.path.join(here, '..', '..', 'native', 'src', 'engine', 'text', 'compose.rs')
with open(target, 'w', encoding='utf8', newline='\n') as out:
    out.write('\n'.join(lines))
print('wrote', os.path.normpath(target), len(pairs), 'pairs')
